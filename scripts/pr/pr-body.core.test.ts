const ATTRIBUTION = ['', '---', '_Generated by [Claude Code](https://claude.ai/code)_'];

function draft(...lines: readonly string[]): string {
  return lines.join('\n');
}

const MINIMAL = draft('# A title', '', 'A description that says what changed.');

function repeatWords(count: number): string {
  return Array.from({ length: count }, (_unused, index) => `word${String(index)}`).join(' ');
}

describe('countable', () => {
  it('counts letters and digits and ignores punctuation and spaces', () => {
    expect(countable('ab, c! 12')).toBe(5);
  });

  it('counts accented letters, because the operator writes French', () => {
    expect(countable('éàü')).toBe(3);
  });

  it('ignores a link target while keeping the text a reader actually reads', () => {
    expect(countable('[ADR17](docs/adr/0017-a-very-long-file-name.md)')).toBe(5);
  });

  it('ignores html markup', () => {
    expect(countable('<summary>ab</summary>')).toBe(2);
  });

  it('counts nothing in an empty string', () => {
    expect(countable('')).toBe(0);
  });
});

describe('stripAttribution', () => {
  it('drops the footer and the rule above it', () => {
    expect(stripAttribution(['body', ...ATTRIBUTION])).toEqual(['body']);
  });

  it('drops the footer alone when no rule precedes it', () => {
    expect(stripAttribution(['body', '_Generated by [Claude Code](x)_'])).toEqual(['body']);
  });

  it('keeps a body that carries no footer', () => {
    expect(stripAttribution(['body'])).toEqual(['body']);
  });
});

describe('parseBody', () => {
  it('reads the title, the description and the sections', () => {
    const parsed = parseBody(draft('# T', '', 'D', '## Notable', '- one'));
    expect(parsed.title).toBe('T');
    expect(parsed.description).toBe('D');
    expect([...parsed.sections.keys()]).toEqual(['Notable']);
  });

  it('answers an empty title when no heading opens the draft', () => {
    expect(parseBody('no heading').title).toBe('');
  });
});

describe('readTableRows', () => {
  it('splits a row into trimmed cells', () => {
    expect(readTableRows(['| a | b |', 'prose'])).toEqual([['a', 'b']]);
  });
});

describe('isSeparatorRow', () => {
  it('recognises a separator and rejects a data row', () => {
    expect(isSeparatorRow(['---', ':--'])).toBe(true);
    expect(isSeparatorRow(['---', 'a'])).toBe(false);
  });
});

describe('readMermaidNodes', () => {
  it('counts each identifier once across arrows and labels', () => {
    const nodes = readMermaidNodes(['```mermaid', 'flowchart TD', 'a -->|label| b', 'b --> a', '']);
    expect([...nodes].sort()).toEqual(['a', 'b']);
  });

  it('skips a line carrying no identifier', () => {
    expect(readMermaidNodes(['-->'])).toEqual([]);
  });

  it('skips the subgraph and end keywords', () => {
    expect(readMermaidNodes(['subgraph one', 'end'])).toEqual([]);
  });
});

describe('readDetailsBlocks', () => {
  it('reads the summary and the body of each block', () => {
    const blocks = readDetailsBlocks(['<details>', '<summary>S</summary>', '', 'B', '</details>']);
    expect(blocks).toEqual([{ summary: 'S', body: 'B' }]);
  });

  it('reads a block that never opened as no block at all', () => {
    expect(readDetailsBlocks(['B', '</details>'])).toEqual([]);
  });

  it('ignores a line outside any block', () => {
    expect(readDetailsBlocks(['outside'])).toEqual([]);
  });
});

describe('readFencedBlocks and withoutFencedLines', () => {
  it('reads the lines inside a fence', () => {
    expect(readFencedBlocks(['```sh', 'run me', '```'])).toEqual([['run me']]);
  });

  it('drops the fenced lines and keeps the prose', () => {
    expect(withoutFencedLines(['prose', '```', 'code', '```'])).toEqual(['prose']);
  });
});

describe('readDeletedPlaceholders', () => {
  it('finds a placeholder GitHub would delete from a code span', () => {
    expect(readDeletedPlaceholders('run `x --name <secret>`')).toEqual(['<secret>']);
  });

  it('finds nothing in a span carrying a real value', () => {
    expect(readDeletedPlaceholders('run `x --name value`')).toEqual([]);
  });

  it('finds nothing when the body has no code span at all', () => {
    expect(readDeletedPlaceholders('plain prose')).toEqual([]);
  });
});

describe('validateBody', () => {
  it('passes a minimal draft', () => {
    expect(validateBody(MINIMAL)).toEqual([]);
  });

  it('refuses a draft with no title', () => {
    expect(validateBody('just prose')).toContainEqual({
      where: 'Title',
      problem: 'no heading line opening with a hash',
    });
  });

  it('refuses a draft with no description', () => {
    expect(validateBody('# T')).toContainEqual({
      where: 'Description',
      problem: 'no paragraph under the title',
    });
  });

  it('refuses a title over the limit', () => {
    const violations = validateBody(draft(`# ${repeatWords(20)}`, '', 'D'));
    expect(violations.some((violation) => violation.where === 'Title')).toBe(true);
  });

  it('refuses a description over the limit', () => {
    const violations = validateBody(draft('# T', '', repeatWords(60)));
    expect(violations.some((violation) => violation.where === 'Description')).toBe(true);
  });

  it('refuses a section it does not know', () => {
    const violations = validateBody(draft(MINIMAL, '## Rationale', 'text'));
    expect(violations[0]?.where).toBe('Rationale');
  });

  it('refuses a flow carrying more nodes than a reader can hold', () => {
    const edges = Array.from(
      { length: LIMITS.flowNodes + 1 },
      (_unused, index) => `n${String(index)} --> n${String(index + 1)}`,
    );
    const violations = validateBody(draft(MINIMAL, '## Flow', '```mermaid', ...edges, '```'));
    expect(violations.some((violation) => violation.where === 'Flow')).toBe(true);
  });

  it('accepts a flow within the node budget', () => {
    expect(validateBody(draft(MINIMAL, '## Flow', '```mermaid', 'a --> b', '```'))).toEqual([]);
  });

  it('refuses a decisions section with no table', () => {
    expect(validateBody(draft(MINIMAL, '## Decisions', 'prose'))).toContainEqual({
      where: 'Decisions',
      problem: 'section present with no table',
    });
  });

  it('refuses decision columns that are not the agreed ones', () => {
    const violations = validateBody(draft(MINIMAL, '## Decisions', '| What | Why |'));
    expect(violations[0]?.problem).toContain('columns must be');
  });

  it('accepts a decisions table with empty cells, because every cell may be null', () => {
    const table = draft(
      MINIMAL,
      '## Decisions',
      '| Decision | Alternative | Why | Consequences | ADR |',
      '| --- | --- | --- | --- | --- |',
      '| Deezer | MusicBrainz |  |  |  |',
    );
    expect(validateBody(table)).toEqual([]);
  });

  it('refuses a decision cell over its column limit', () => {
    const table = draft(
      MINIMAL,
      '## Decisions',
      '| Decision | Alternative | Why | Consequences | ADR |',
      '| --- | --- | --- | --- | --- |',
      `| ${repeatWords(12)} |  |  |  |  |`,
    );
    const violations = validateBody(table);
    expect(violations[0]?.where).toBe('Decisions row 1 Decision');
  });

  it('refuses more decision rows than the table allows', () => {
    const rows = Array.from({ length: LIMITS.decisionRows + 1 }, () => '| a | b | c | d | e |');
    const table = draft(
      MINIMAL,
      '## Decisions',
      '| Decision | Alternative | Why | Consequences | ADR |',
      '| --- | --- | --- | --- | --- |',
      ...rows,
    );
    const violations = validateBody(table);
    expect(violations.some((violation) => violation.problem.includes('rows, limit'))).toBe(true);
  });

  it('refuses a decision row carrying a sixth cell nobody agreed to', () => {
    const table = draft(
      MINIMAL,
      '## Decisions',
      '| Decision | Alternative | Why | Consequences | ADR |',
      '| --- | --- | --- | --- | --- |',
      `| a | b | c | d | e | ${repeatWords(30)} |`,
    );
    const violations = validateBody(table);
    expect(violations.some((violation) => violation.where.includes('column 6'))).toBe(true);
  });

  it('accepts a before-merge block holding prose and one command', () => {
    const section = draft(
      MINIMAL,
      '## Before merge',
      '<details>',
      '<summary>Seed the credential</summary>',
      '',
      'Spotify stays inert until the parameter exists.',
      '',
      '```sh',
      'aws ssm put-parameter --name /pragma/spotify-credentials',
      '```',
      '</details>',
    );
    expect(validateBody(section)).toEqual([]);
  });

  it('refuses a before-merge section that is not exactly one details block', () => {
    expect(validateBody(draft(MINIMAL, '## Before merge', 'bare prose'))).toContainEqual({
      where: 'Before merge',
      problem: '0 blocks, expected exactly 1',
    });
  });

  it('refuses a second command block', () => {
    const section = draft(
      MINIMAL,
      '## Before merge',
      '<details>',
      '<summary>S</summary>',
      '```sh',
      'one',
      '```',
      '```sh',
      'two',
      '```',
      '</details>',
    );
    expect(validateBody(section)).toContainEqual({
      where: 'Before merge',
      problem: 'more than one command block',
    });
  });

  it('refuses a comment inside the command, which is prose escaping its limit', () => {
    const section = draft(
      MINIMAL,
      '## Before merge',
      '<details>',
      '<summary>S</summary>',
      '```sh',
      '# seed it first',
      'aws ssm put-parameter',
      '```',
      '</details>',
    );
    expect(validateBody(section)).toContainEqual({
      where: 'Before merge',
      problem: 'command block carries a comment',
    });
  });

  it('refuses before-merge prose over the limit while ignoring the command length', () => {
    const section = draft(
      MINIMAL,
      '## Before merge',
      '<details>',
      '<summary>S</summary>',
      repeatWords(60),
      '</details>',
    );
    const violations = validateBody(section);
    expect(violations.some((violation) => violation.where === 'Before merge')).toBe(true);
  });

  it('accepts validation evidence within its limits', () => {
    const section = draft(
      MINIMAL,
      '## Validation',
      '<details>',
      '<summary>Long press</summary>',
      'A held press opened the dialog at phone width.',
      '</details>',
    );
    expect(validateBody(section)).toEqual([]);
  });

  it('refuses a validation title over the limit', () => {
    const section = draft(
      MINIMAL,
      '## Validation',
      '<details>',
      `<summary>${repeatWords(8)}</summary>`,
      'short',
      '</details>',
    );
    const violations = validateBody(section);
    expect(violations[0]?.where).toBe('Validation item 1 title');
  });

  it('refuses a validation body over the limit', () => {
    const section = draft(
      MINIMAL,
      '## Validation',
      '<details>',
      '<summary>S</summary>',
      repeatWords(30),
      '</details>',
    );
    expect(validateBody(section)).toContainEqual({
      where: 'Validation item 1',
      problem: '170 countable chars, limit 100',
    });
  });

  it('refuses more validation items than a reviewer will open', () => {
    const items = Array.from({ length: LIMITS.evidenceItems + 1 }, () =>
      draft('<details>', '<summary>S</summary>', 'body', '</details>'),
    );
    const violations = validateBody(draft(MINIMAL, '## Validation', ...items));
    expect(violations.some((violation) => violation.problem.includes('items, limit'))).toBe(true);
  });

  it('refuses a notable fact over the limit', () => {
    const violations = validateBody(draft(MINIMAL, '## Notable', `- ${repeatWords(30)}`));
    expect(violations[0]?.where).toBe('Notable fact 1');
  });

  it('accepts notable facts within the limit', () => {
    expect(validateBody(draft(MINIMAL, '## Notable', '- Deezer needs no key.'))).toEqual([]);
  });

  it('refuses a placeholder GitHub silently deletes', () => {
    const violations = validateBody(draft(MINIMAL, '## Notable', '- run `x --value <secret>`'));
    expect(violations.some((violation) => violation.where === 'Body')).toBe(true);
  });

  it('ignores the attribution footer when counting', () => {
    expect(validateBody(draft(MINIMAL, ...ATTRIBUTION))).toEqual([]);
  });
});

