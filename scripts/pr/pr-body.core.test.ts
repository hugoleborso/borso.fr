describe('the parts a careless edit would silently change', () => {
  it('treats a rule on the very first line as the start of the footer', () => {
    expect(stripAttribution(['---', '_Generated by [Claude Code](x)_'])).toEqual([]);
  });

  it('sees a fence opened with indentation, so a heading inside it stays text', () => {
    const section = draft(MINIMAL, '## Notable', '  ```sh', '## fake section', '  ```');
    expect(validateBody(section)).toEqual([]);
  });

  it('skips an indented mermaid keyword rather than counting it as a node', () => {
    expect(readMermaidNodes(['  subgraph one', '  end'])).toEqual([]);
  });

  it('keeps a closing tag that only ends a line as part of the body', () => {
    const blocks = readDetailsBlocks(['<details>', 'text</details>', '</details>']);
    expect(blocks).toEqual([{ summary: '', body: 'text</details>' }]);
  });

  it('keeps the line breaks of a details body', () => {
    const blocks = readDetailsBlocks(['<details>', 'one', 'two', '</details>']);
    expect(blocks[0]?.body).toBe('one\ntwo');
  });

  it('trims a summary written with spaces inside the tag', () => {
    expect(
      readDetailsBlocks(['<details>', '<summary> S </summary>', '</details>'])[0]?.summary,
    ).toBe('S');
  });

  it('drops indented fenced lines and keeps the prose around them', () => {
    expect(withoutFencedLines(['  ```', 'code', '  ```', 'prose'])).toEqual(['prose']);
  });

  it('counts each line of a block and adds them up', () => {
    expect(countableLines(['ab', 'c!'])).toBe(3);
  });

  it('leaves the command out of the before-merge count', () => {
    const section = draft(
      MINIMAL,
      '## Before merge',
      '<details>',
      '<summary>S</summary>',
      'a'.repeat(LIMITS.beforeMerge),
      '```sh',
      'aws ssm put-parameter --name /pragma/spotify-credentials --type SecureString',
      '```',
      '</details>',
    );
    expect(validateBody(section)).toEqual([]);
  });

  it('reads only list items as notable facts', () => {
    const paragraph = repeatWords(40);
    expect(validateBody(draft(MINIMAL, '## Notable', paragraph))).toEqual([]);
  });

  it('renders the body line by line, fences and section headings intact', () => {
    const rendered = renderBody(draft('# T', '', 'D', '## Notable', '  ```sh', '# cmd', '  ```'));
    expect(rendered).toBe('D\n## Notable\n  ```sh\n# cmd\n  ```');
  });
});

describe('a heading block, which is what survives the GitHub body sanitizer', () => {
  it('reads a heading and the lines under it as one block', () => {
    expect(readHeadingBlocks(['### T', 'body'])).toEqual([{ summary: 'T', body: 'body' }]);
  });

  it('closes one heading block when the next opens', () => {
    expect(readHeadingBlocks(['### A', 'one', '### B', 'two'])).toEqual([
      { summary: 'A', body: 'one' },
      { summary: 'B', body: 'two' },
    ]);
  });

  it('keeps each block line-separated and drops the blank lines around it', () => {
    const lines = ['### A', '', 'one', 'two', '', '### B', '', 'three', ''];
    expect(readHeadingBlocks(lines)).toEqual([
      { summary: 'A', body: 'one\ntwo' },
      { summary: 'B', body: 'three' },
    ]);
  });

  it('ignores the lines before the first heading', () => {
    expect(readHeadingBlocks(['loose', '### T', 'body'])).toEqual([{ summary: 'T', body: 'body' }]);
  });

  it('reads nothing from lines carrying no heading', () => {
    expect(readHeadingBlocks(['loose'])).toEqual([]);
  });

  it('trims a heading written with a trailing space', () => {
    expect(readHeadingBlocks(['### T ', 'b'])[0]?.summary).toBe('T');
  });

  it('keeps the line breaks under a heading', () => {
    expect(readHeadingBlocks(['### T', 'one', 'two'])[0]?.body).toBe('one\ntwo');
  });

  it('prefers a toggle when the section carries one', () => {
    const lines = ['<details>', '<summary>S</summary>', 'b', '</details>', '### H', 'c'];
    expect(readBlocks(lines)).toEqual([{ summary: 'S', body: 'b' }]);
  });

  it('falls back to headings when the section carries no toggle', () => {
    expect(readBlocks(['### H', 'c'])).toEqual([{ summary: 'H', body: 'c' }]);
  });

  it('accepts a before-merge section written as a heading', () => {
    const section = draft(
      MINIMAL,
      '## Before merge',
      '### Seed the credential',
      'Spotify stays inert until the parameter exists.',
      '```sh',
      'aws ssm put-parameter --name /pragma/spotify-credentials',
      '```',
    );
    expect(validateBody(section)).toEqual([]);
  });

  it('accepts validation evidence written as headings', () => {
    const section = draft(
      MINIMAL,
      '## Validation',
      '### Long press',
      'A held press opened the dialog at phone width.',
      '### Live search',
      'Deezer answered 25 ranked hits through the dev API.',
    );
    expect(validateBody(section)).toEqual([]);
  });

  it('refuses a heading-written validation body over the limit', () => {
    const section = draft(MINIMAL, '## Validation', '### T', repeatWords(30));
    expect(validateBody(section)).toContainEqual({
      where: 'Validation item 1',
      problem: '170 countable chars, limit 100',
    });
  });

  it('refuses two before-merge blocks written as headings', () => {
    const section = draft(MINIMAL, '## Before merge', '### One', 'a', '### Two', 'b');
    expect(validateBody(section)).toContainEqual({
      where: 'Before merge',
      problem: '2 blocks, expected exactly 1',
    });
  });
});

describe('the sweep shape, which a kaizen body uses instead', () => {
  const SWEEP = draft(
    '# docs: lessons from PR 1',
    '',
    'Twenty-three rows swept, twelve already eradicated.',
    '## Inventory',
    '| Decision | Rows |',
    '| --- | --- |',
    '| dantotsu | 3 |',
    '## Shipped',
    '| Entry | Level | Now impossible |',
    '| --- | --- | --- |',
    '| [a](docs/dantotsus/a.md) | 1 | A reader cannot get it wrong |',
    '## Patterns',
    '- The file excused from the gates is the one that broke.',
  );

  it('accepts a sweep body', () => {
    expect(validateBody(SWEEP)).toEqual([]);
  });

  it('refuses a body mixing a feature section into a sweep', () => {
    const mixed = draft(SWEEP, '## Notable', '- a fact');
    expect(validateBody(mixed)).toContainEqual({
      where: 'Body',
      problem: `a body is a feature (${FEATURE_SECTIONS.join(', ')}) or a sweep (${SWEEP_SECTIONS.join(', ')}), never both`,
    });
  });

  it('holds a body carrying one sweep section to the whole-body limit, mixed or not', () => {
    const mixedAndWide = draft(SWEEP, '## Notable', `- ${repeatWords(200)}`);
    const problems = validateBody(mixedAndWide)
      .filter((violation) => violation.where === 'Body')
      .map((violation) => violation.problem);
    expect(problems).toHaveLength(2);
    expect(problems.some((problem) => problem.includes('limit 700'))).toBe(true);
    expect(problems.some((problem) => problem.includes('never both'))).toBe(true);
  });

  it('holds a sweep body to the whole-body limit', () => {
    const wide = draft(SWEEP.replace('| dantotsu | 3 |', `| ${repeatWords(200)} | 3 |`));
    const violations = validateBody(wide);
    expect(violations.some((violation) => violation.where === 'Body')).toBe(true);
  });

  it('leaves a feature body free of the whole-body limit', () => {
    const wide = draft(
      MINIMAL,
      '## Notable',
      `- ${'a'.repeat(LIMITS.notableFact)}`,
      `- ${'b'.repeat(LIMITS.notableFact)}`,
      `- ${'c'.repeat(LIMITS.notableFact)}`,
      `- ${'d'.repeat(LIMITS.notableFact)}`,
      `- ${'e'.repeat(LIMITS.notableFact)}`,
      `- ${'f'.repeat(LIMITS.notableFact)}`,
      `- ${'g'.repeat(LIMITS.notableFact)}`,
      `- ${'h'.repeat(LIMITS.notableFact)}`,
    );
    expect(validateBody(wide)).toEqual([]);
  });

  it('refuses each sweep section over its own limit', () => {
    for (const [name, limit] of [
      ['Inventory', LIMITS.inventory],
      ['Shipped', LIMITS.shipped],
      ['Patterns', LIMITS.patterns],
    ] as const) {
      const body = draft('# T', '', 'D', `## ${name}`, 'a'.repeat(limit + 1));
      expect(validateBody(body)).toContainEqual({
        where: name,
        problem: `${String(limit + 1)} countable chars, limit ${String(limit)}`,
      });
    }
  });

  it('leaves a command block out of the whole-body count', () => {
    const withCode = draft(SWEEP, '', '```sh', 'a'.repeat(LIMITS.whole), '```');
    expect(validateBody(withCode)).toEqual([]);
  });
});

