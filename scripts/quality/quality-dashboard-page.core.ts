import {
  judgeAgainstTarget,
  type Indicator,
  type Pillar,
  type Target,
  type WeeklyValue,
} from './quality-dashboard.core';
import { escapeHtml, renderQualityPage } from './quality-page.core';
import { renderEngagedWeakPoints, renderVaricelle, type PlacedDot } from './weak-points-page.core';
import type { EngagedWeakPoint, WeeklyCount } from './weak-points.core';

export interface DashboardPageInput {
  readonly now: string;
  readonly indicators: readonly Indicator[];
  readonly targets: readonly Target[];
  readonly unavailableSources: readonly string[];
  readonly placed: readonly PlacedDot[];
  readonly engaged: readonly EngagedWeakPoint[];
  readonly weeklyCounts: ReadonlyMap<string, readonly WeeklyCount[]>;
}

const PILLARS: readonly { readonly id: Pillar; readonly title: string; readonly intent: string }[] =
  [
    {
      id: 'security',
      title: 'Security',
      intent: 'Known vulnerable dependencies and exposed secrets, counted, never named.',
    },
    {
      id: 'stability',
      title: 'Stability',
      intent: 'Errors on previews and in production, and bugs users reported.',
    },
    { id: 'speed', title: 'Speed', intent: 'What a caller of each production API waits.' },
  ];

const UNIT_SUFFIX: Readonly<Record<Indicator['unit'], string>> = { count: '', ms: ' ms' };
const PERCENT = 100;

function renderTrend(weeks: readonly WeeklyValue[]): string {
  if (weeks.every((week) => week.value === null)) return '';
  const highest = Math.max(1, ...weeks.map((week) => week.value ?? 0));
  const bars = weeks.map((week) => {
    if (week.value === null) {
      return `<span class="bar missing" title="week of ${week.weekStart}: no data"></span>`;
    }
    const height = Math.round((week.value / highest) * PERCENT);
    const zero = week.value === 0 ? ' zero' : '';
    return `<span class="bar${zero}" style="height:${String(height)}%" title="week of ${week.weekStart}: ${String(week.value)}"></span>`;
  });
  return `<div class="bars small" aria-label="eight-week trend">${bars.join('')}</div>`;
}

function renderValue(indicator: Indicator, targets: readonly Target[]): string {
  if (indicator.status.kind !== 'ok') {
    const prefix = indicator.status.kind === 'unavailable' ? 'unavailable: ' : '';
    return `<span class="status">${escapeHtml(prefix + indicator.status.reason)}</span>`;
  }
  if (indicator.current === null) return '<span class="status">no traffic</span>';
  const verdict = judgeAgainstTarget(indicator, targets);
  const verdictClass = verdict === 'none' ? '' : ` ${verdict}`;
  return `<span class="value${verdictClass}">${String(indicator.current)}${UNIT_SUFFIX[indicator.unit]}</span>${renderTrend(indicator.weeks)}`;
}

function orderedUnique(values: readonly string[]): readonly string[] {
  return [...new Set(values)];
}

export function renderPillar(
  pillar: (typeof PILLARS)[number],
  indicators: readonly Indicator[],
  targets: readonly Target[],
): string {
  const own = indicators.filter((indicator) => indicator.pillar === pillar.id);
  const labels = orderedUnique(own.map((indicator) => indicator.label));
  const apps = orderedUnique(own.map((indicator) => indicator.app));
  const header = `<tr><th></th>${labels.map((label) => `<th>${escapeHtml(label)}</th>`).join('')}</tr>`;
  const rows = apps.map((app) => {
    const cells = labels.map((label) => {
      const indicator = own.find((candidate) => candidate.app === app && candidate.label === label);
      return `<td>${indicator === undefined ? '' : renderValue(indicator, targets)}</td>`;
    });
    return `<tr><th>${escapeHtml(app)}</th>${cells.join('')}</tr>`;
  });
  return `<section class="pillar"><h2>${pillar.title}</h2><p>${pillar.intent}</p><div class="scroll"><table>${header}${rows.join('')}</table></div></section>`;
}

function renderBanner(unavailableSources: readonly string[]): string {
  if (unavailableSources.length === 0) return '';
  const items = unavailableSources.map((source) => `<li>${escapeHtml(source)}</li>`);
  return `<div class="banner" role="status"><strong>Some sources could not be read on this run.</strong><ul>${items.join('')}</ul></div>`;
}

export function renderDashboardPage(input: DashboardPageInput): string {
  const pillars = PILLARS.map((pillar) => renderPillar(pillar, input.indicators, input.targets));
  const targetNote =
    input.targets.length === 0
      ? 'No target is set yet, so no value is coloured. Targets are written in docs/quality/targets.md.'
      : 'A value is green within its target and red over it, per docs/quality/targets.md.';
  return renderQualityPage(
    'Quality dashboard',
    `<p>Generated by scripts/quality/quality-dashboard.ts on ${input.now}. Each value covers the last seven days; the bars beside it are the last eight weeks, oldest first. ${targetNote}</p>
${renderBanner(input.unavailableSources)}
<div class="pillars">${pillars.join('')}</div>
<h2>Engaged weak points</h2>
${renderEngagedWeakPoints(input.engaged, input.weeklyCounts)}
<h2>Defect map</h2>
<p>One dot per defect, placed where it lived and coloured by the stage that caught it. A dantotsu gives its stage through <code>detected-at:</code>; a bug report filed in pragma is stage E and sits on pragma's row.</p>
${renderVaricelle(input.placed, input.now)}`,
  );
}
