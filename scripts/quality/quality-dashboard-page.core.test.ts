import { describe, expect, it } from 'vitest';
import {
  renderDashboardPage,
  type DashboardPageInput,
  type RangeView,
} from './quality-dashboard-page.core';
import type { Indicator } from './quality-dashboard.core';
import type { PlacedDot } from './weak-points-page.core';
import type { DefectDot, EngagedWeakPoint } from './weak-points.core';

const NOW = '2026-10-13';

function indicator(overrides: Partial<Indicator>): Indicator {
  return {
    id: 'latency-p95',
    pillar: 'speed',
    label: 'p95',
    unit: 'ms',
    app: 'pragma',
    current: 1391,
    points: [
      { label: '2026-10-05', value: 1000 },
      { label: '2026-10-12', value: 2000 },
    ],
    status: { kind: 'ok' },
    ...overrides,
  };
}

function weakPoint(overrides: Partial<EngagedWeakPoint>): EngagedWeakPoint {
  return {
    id: 'gate-measures-nothing',
    title: 'A gate reports green while measuring nothing',
    map: 'factory',
    engagedOn: '2026-10-10',
    countermeasure: 'Plant one defect per gate',
    isClosed: false,
    ...overrides,
  };
}

function placedDot(overrides: Partial<DefectDot>, map: PlacedDot['map']): PlacedDot {
  return {
    dot: {
      slug: 'a-defect',
      title: 'A defect',
      date: '2026-10-12',
      zone: 'apps/pragma',
      weakPoint: null,
      recurs: [],
      stage: 'C',
      link: 'https://example.test/a',
      ...overrides,
    },
    map,
    row: map === 'product' ? 'apps/pragma' : 'gates',
    column: map === 'product' ? 'site' : 'defects',
  };
}

type InputOverrides = Partial<Omit<DashboardPageInput, 'ranges'>> & {
  readonly indicators?: readonly Indicator[];
  readonly ranges?: readonly RangeView[];
};

function buildInput(overrides: InputOverrides = {}): DashboardPageInput {
  const { indicators, ranges, ...rest } = overrides;
  return {
    now: NOW,
    ranges: ranges ?? [
      { id: 'week', title: 'week by week', indicators: indicators ?? [indicator({})] },
    ],
    security: [],
    targets: [],
    placed: [],
    engaged: [],
    weeklyCounts: new Map(),
    ...rest,
  };
}

describe('renderDashboardPage', () => {
  it('opens with the title, keeps the generation note in its tooltip and ships no script', () => {
    const html = renderDashboardPage(buildInput());
    expect(
      html.startsWith(
        '<title>borso.fr 3S board</title>\n<meta name="claude:viewport-fit-sides" content="cover">\n<style>',
      ),
    ).toBe(true);
    expect(html).not.toContain('<!doctype');
    expect(html).toContain(':root[data-theme="dark"]{');
    expect(html).toContain(
      '<h1 title="Generated by scripts/quality/quality-dashboard.ts on 2026-10-13. ',
    );
    expect(html).not.toContain('<script');
    expect(html).not.toContain('<dialog');
    expect(html).not.toContain('<p>');
  });

  it('draws five toggles: speed, stability, security, weak points, defect map', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({}),
          indicator({ id: 'errors-prod', pillar: 'stability', label: '5xx', unit: 'count' }),
        ],
        security: [
          indicator({
            id: 'audit-other',
            pillar: 'security',
            label: 'pnpm audit, moderate or lower',
            unit: 'count',
            app: 'repository',
            current: 26,
            points: [],
          }),
        ],
      }),
    );
    const order = [
      '<h2>Speed</h2>',
      '<h2>Stability</h2>',
      '<h2>Security</h2>',
      '<h2>Engaged weak points</h2>',
      '<h2>Defect map</h2>',
    ].map((heading) => html.indexOf(heading));
    expect(order).toStrictEqual([...order].sort((first, second) => first - second));
    expect(order[0]).toBeGreaterThan(0);
    expect(html).toContain(
      '<details class="section section-speed"><summary title="Latency of each production API, in milliseconds, over the selected range."><h2>Speed</h2><span class="score unjudged">no ceiling</span></summary><div class="rows">',
    );
  });

  it('closes a row on one pastille per application and a score', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({ app: 'pragma', current: 2845 }),
          indicator({ app: 'talos', current: 1995 }),
        ],
        targets: [
          { indicatorId: 'latency-p95', app: 'pragma', ceiling: 2000 },
          { indicatorId: 'latency-p95', app: 'talos', ceiling: 2000 },
        ],
      }),
    );
    expect(html).toContain(
      '<summary><span class="row-name">p95</span><span class="pips"><span class="flag ko" title="pragma · p95 · 2845 ms · over the ceiling of 2000 ms"></span><span class="flag ok" title="talos · p95 · 1995 ms · at or under the ceiling of 2000 ms"></span></span><span class="score ko">1/2 ok</span></summary>',
    );
  });

  it('opens a row on every value with its ceiling', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({ app: 'pragma', current: 2845 }),
          indicator({
            app: 'borso-fr',
            current: null,
            points: [{ label: '2026-10-12', value: null }],
            status: { kind: 'not-applicable', reason: 'no API' },
          }),
        ],
        targets: [{ indicatorId: 'latency-p95', app: 'pragma', ceiling: 2000 }],
      }),
    );
    expect(html).toContain(
      '<summary class="chip" title="pragma · p95 · 2845 ms · over the ceiling of 2000 ms"><span class="chip-head"><span class="flag ko"></span><span class="chip-app">pragma</span></span><span class="chip-value">2845 ms</span><span class="chip-goal">≤ 2000 ms</span>',
    );
    expect(html).toContain(
      '<span class="chip flat" title="borso-fr · p95 · no API"><span class="chip-head"><span class="flag unjudged"></span><span class="chip-app">borso-fr</span></span><span class="chip-value">—</span><span class="chip-goal">no ceiling</span></span>',
    );
  });

  it('marks a section ok when every judged indicator is at or under its ceiling', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [indicator({ current: 2000 })],
        targets: [{ indicatorId: 'latency-p95', app: 'pragma', ceiling: 2000 }],
      }),
    );
    expect(html).toContain('<span class="score ok">1/1 ok</span>');
  });

  it('opens a graph as a toggle holding a full chart with axis, gridlines, hover and legend', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({
            points: [
              { label: '2026-09-28', value: null },
              { label: '2026-10-05', value: 0 },
              { label: '2026-10-12', value: 4 },
            ],
          }),
        ],
        targets: [{ indicatorId: 'latency-p95', app: 'pragma', ceiling: 2 }],
      }),
    );
    expect(html).toContain(
      '<details class="zoomable" name="chart-zoom" id="speed-latency-p95-pragma"><summary class="chip" title="pragma · p95 · 1391 ms · over the ceiling of 2 ms"><span class="chip-head">',
    );
    expect(html).toContain(
      '<span class="bar missing" title="2026-09-28: no data"></span><span class="bar zero" style="height:0%" title="2026-10-05: 0 ms"></span><span class="bar" style="height:100%" title="2026-10-12: 4 ms"></span></span></summary>',
    );
    expect(html).toContain(
      '<span class="y-axis"><span class="tick" style="bottom:0%">0 ms</span><span class="tick" style="bottom:25%">1 ms</span><span class="tick" style="bottom:50%">2 ms</span><span class="tick" style="bottom:75%">3 ms</span><span class="tick" style="bottom:100%">4 ms</span></span>',
    );
    expect(html).toContain('<span class="gridline" style="bottom:75%"></span>');
    expect(html).toContain('<span class="ceiling" style="bottom:50%" title="ceiling 2 ms"></span>');
    expect(html).toContain(
      '<span class="col" title="2026-10-12: 4 ms"><span class="bar" style="height:100%"><span class="week-value">4 ms</span></span></span>',
    );
    expect(html).toContain('<span class="col"><span class="bar missing"></span></span>');
    expect(html).toContain(
      '<span class="x-axis"><span class="x-pad"></span><span class="x-weeks"><span>09-28</span><span>10-05</span><span>10-12</span></span></span>',
    );
    expect(html).toContain(
      '<span class="chart-legend"><span><i class="swatch"></i>weekly value</span><span><i class="swatch rule"></i>ceiling 2 ms</span></span>',
    );
  });

  it('rounds the axis up to a clean step above the tallest week', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({
            unit: 'count',
            points: [
              { label: '2026-10-05', value: 153 },
              { label: '2026-10-12', value: 544 },
            ],
          }),
        ],
      }),
    );
    expect(html).toContain('<span class="tick" style="bottom:100%">600</span>');
    expect(html).toContain('<span class="tick" style="bottom:33%">200</span>');
    expect(html).toContain(
      '<span class="bar" style="height:91%"><span class="week-value">544</span></span>',
    );
    expect(html).toContain(
      '<span class="col" title="2026-10-05: 153"><span class="bar" style="height:26%"></span></span>',
    );
  });

  it('picks a clean axis step at each magnitude', () => {
    const steps = [
      { value: 7, top: '8' },
      { value: 30, top: '30' },
      { value: 2845, top: '3000' },
      { value: 9000, top: '10000' },
    ];
    for (const step of steps) {
      const html = renderDashboardPage(
        buildInput({
          indicators: [
            indicator({ unit: 'count', points: [{ label: '2026-10-12', value: step.value }] }),
          ],
        }),
      );
      expect(html).toContain(`<span class="tick" style="bottom:100%">${step.top}</span>`);
    }
  });

  it('draws no ceiling line and no legend entry when the ceiling sits above the axis', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [indicator({ points: [{ label: '2026-10-12', value: 4 }] })],
        targets: [{ indicatorId: 'latency-p95', app: 'pragma', ceiling: 900 }],
      }),
    );
    expect(html).toContain('class="panel"');
    expect(html).not.toContain('class="ceiling"');
    expect(html).toContain(
      '<span class="chart-legend"><span><i class="swatch"></i>weekly value</span></span>',
    );
  });

  it('draws no graph at all when no week of the row holds a value', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [indicator({ points: [{ label: '2026-10-12', value: null }] })],
      }),
    );
    expect(html).toContain(
      '<div class="chips"><span class="chip flat" title="pragma · p95 · no ceiling in docs/quality/targets.md, so neither ok nor ko">',
    );
    expect(html).not.toContain('class="zoomable"');
  });

  it('says in the tooltip why an indicator holds no value', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({
            app: 'a',
            current: null,
            status: { kind: 'unavailable', reason: 'token <expired>' },
          }),
          indicator({ app: 'c', current: null, points: [{ label: '2026-10-12', value: 3 }] }),
        ],
      }),
    );
    expect(html).toContain('title="a · p95 · token &lt;expired&gt;"');
    expect(html).toContain('title="c · p95 · no traffic in the rolling seven days"');
  });

  it('warns inside the section whose source could not be read, once per reason', () => {
    const html = renderDashboardPage(
      buildInput({
        security: [
          indicator({
            id: 'dependabot-other',
            pillar: 'security',
            app: 'repository',
            current: null,
            status: { kind: 'unavailable', reason: 'the token lacks the permission' },
          }),
          indicator({
            id: 'dependabot-critical-high',
            pillar: 'security',
            label: 'Dependabot, critical or high',
            app: 'repository',
            current: null,
            status: { kind: 'unavailable', reason: 'the token lacks the permission' },
          }),
          indicator({
            id: 'secret-scanning-open',
            pillar: 'security',
            label: 'Secret scanning, open',
            app: 'repository',
            current: null,
            status: { kind: 'unavailable', reason: 'the proxy refuses the path' },
          }),
        ],
      }),
    );
    expect(html).toContain(
      '<span class="warn" role="img" aria-label="a source could not be read" title="the token lacks the permission · the proxy refuses the path">⚠</span></summary>',
    );
  });

  it('scores the engaged weak points on the current week and opens each on its graph', () => {
    const html = renderDashboardPage(
      buildInput({
        engaged: [
          weakPoint({}),
          weakPoint({ id: 'quiet-one', title: 'A quiet weak point' }),
          weakPoint({ id: 'no-series', title: 'A weak point with no week' }),
          weakPoint({ id: 'closed-one', title: 'A closed weak point', isClosed: true }),
        ],
        weeklyCounts: new Map([
          [
            'gate-measures-nothing',
            [
              { weekStart: '2026-10-05', count: 1 },
              { weekStart: '2026-10-12', count: 2 },
            ],
          ],
          ['quiet-one', [{ weekStart: '2026-10-12', count: 0 }]],
        ]),
      }),
    );
    expect(html).toContain('<h2>Engaged weak points</h2><span class="score ko">1/2 ok</span>');
    expect(html).toContain(
      '<span class="row-name">A gate reports green while measuring nothing</span><span class="pips"><span class="flag ko" title="A gate reports green while measuring nothing · factory map · engaged on 2026-10-10 · 3 occurrence(s) recorded · countermeasure: Plant one defect per gate · 2 in the week of 2026-10-12. Target: zero per week."></span></span><span class="score ko">0/1 ok</span>',
    );
    expect(html).toContain('<span class="chip-app">quiet-one</span>');
    expect(html).toContain('id="weak-gate-measures-nothing"');
    expect(html).toContain('<span class="chip-value">—</span>');
    expect(html).toContain('no occurrence yet. Target: zero per week.');
    expect(html).not.toContain('A closed weak point');
  });

  it('offers one tab per range and shows only the first', () => {
    const html = renderDashboardPage(
      buildInput({
        ranges: [
          { id: 'week', title: 'week by week', indicators: [indicator({})] },
          {
            id: 'hour',
            title: 'last 12 hours',
            indicators: [indicator({ points: [{ label: '14:00', value: 7 }] })],
          },
        ],
      }),
    );
    expect(html).toContain(
      '<input type="radio" class="range-pick" name="range" id="range-week" checked><input type="radio" class="range-pick" name="range" id="range-hour">',
    );
    expect(html).toContain(
      '<label class="range-tab" for="range-week">week by week</label><label class="range-tab" for="range-hour">last 12 hours</label>',
    );
    expect(html).toContain('<div class="range-panel" data-range="hour">');
    expect(html).toContain('<span>14:00</span>');
    expect(html).toContain('title="14:00: 7 ms"');
  });

  it('counts the defects and gives the product and factory maps their own toggle', () => {
    const html = renderDashboardPage(
      buildInput({
        placed: [
          placedDot({}, 'product'),
          placedDot({ slug: 'b', title: 'B' }, 'product'),
          placedDot({ slug: 'c', title: 'C' }, 'factory'),
        ],
      }),
    );
    expect(html).toContain('<h2>Defect map</h2><span class="score unjudged">3 defects</span>');
    expect(html).toContain(
      '<span title="A: caught locally or by a gate"><span class="dot stage-a">',
    );
    expect(html).toContain(
      '<span class="row-name">Product map</span><span class="pips"></span><span class="score unjudged">2 dots</span></summary><div class="map" title="Applications and infrastructure packages by layer',
    );
    expect(html).toContain(
      '<span class="score unjudged">1 dots</span></summary><div class="map" title="The stations of the line',
    );
    expect(html).toContain('<th>apps/pragma (2)</th>');
    expect(html).toContain('<th>gates (1)</th>');
  });
});
