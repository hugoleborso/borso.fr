import { describe, expect, it } from 'vitest';
import { renderDashboardPage, type DashboardPageInput } from './quality-dashboard-page.core';
import type { Indicator } from './quality-dashboard.core';

const NOW = '2026-10-13';

function indicator(overrides: Partial<Indicator>): Indicator {
  return {
    id: 'latency-p95',
    pillar: 'speed',
    label: 'p95',
    unit: 'ms',
    app: 'pragma',
    current: 1391,
    weeks: [
      { weekStart: '2026-10-05', value: 1000 },
      { weekStart: '2026-10-12', value: 2000 },
    ],
    status: { kind: 'ok' },
    ...overrides,
  };
}

function buildInput(overrides: Partial<DashboardPageInput> = {}): DashboardPageInput {
  return {
    now: NOW,
    indicators: [indicator({})],
    targets: [],
    placed: [],
    engaged: [],
    weeklyCounts: new Map(),
    ...overrides,
  };
}

describe('renderDashboardPage', () => {
  it('opens with the title and keeps the generation note in its tooltip', () => {
    const html = renderDashboardPage(buildInput());
    expect(
      html.startsWith(
        '<title>borso.fr 3S board</title>\n<meta name="claude:viewport-fit-sides" content="cover">\n<style>',
      ),
    ).toBe(true);
    expect(html).not.toContain('<!doctype');
    expect(html).toContain(':root[data-theme="dark"]{');
    expect(html).toContain(
      '<h1 title="Generated by scripts/quality/quality-dashboard.ts on 2026-10-13. Each indicator is the rolling seven days, and is ok or ko against its ceiling in docs/quality/targets.md. A closed section shows how many of its indicators are ok. Opening an indicator shows its last eight weeks, oldest first. Hover anything for its detail.">borso.fr 3S board</h1>',
    );
    expect(html).not.toContain('class="banner"');
    expect(html).not.toContain('<p>');
  });

  it('draws speed, then stability, then security, each as its own toggle', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({}),
          indicator({ id: 'errors-prod', pillar: 'stability', label: '5xx', unit: 'count' }),
          indicator({
            id: 'audit-other',
            pillar: 'security',
            label: 'pnpm audit, moderate or lower',
            unit: 'count',
            app: 'repository',
            current: 26,
            weeks: [{ weekStart: '2026-10-12', value: null }],
          }),
        ],
      }),
    );
    expect(html.indexOf('<h2>Speed</h2>')).toBeLessThan(html.indexOf('<h2>Stability</h2>'));
    expect(html.indexOf('<h2>Stability</h2>')).toBeLessThan(html.indexOf('<h2>Security</h2>'));
    expect(html).toContain(
      '<details class="pillar pillar-speed"><summary title="Latency of each production API, in milliseconds."><h2>Speed</h2><span class="score unjudged">0/0 ok</span></summary><div class="rows">',
    );
    expect(html).toContain('<span class="who">pnpm audit, moderate or lower</span>');
    expect(html).toContain('<span class="amount">26</span>');
    expect(html).toContain('<span class="amount">1391 ms</span>');
  });

  it('scores a section on the indicators that have a ceiling and puts the failing ones first', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({ app: 'talos', current: 1995 }),
          indicator({ app: 'pragma', current: 2845 }),
          indicator({ app: 'banana-rush', current: null, status: { kind: 'ok' } }),
        ],
        targets: [
          { indicatorId: 'latency-p95', app: 'talos', ceiling: 2000 },
          { indicatorId: 'latency-p95', app: 'pragma', ceiling: 2000 },
        ],
      }),
    );
    expect(html).toContain('<span class="score ko">1/2 ok</span>');
    expect(html.indexOf('pragma · p95')).toBeLessThan(html.indexOf('talos · p95'));
    expect(html.indexOf('talos · p95')).toBeLessThan(html.indexOf('banana-rush · p95'));
    expect(html).toContain(
      '<summary title="latency-p95 · over the ceiling of 2000 ms"><span class="flag ko"></span><span class="who">pragma · p95</span><span class="amount">2845 ms</span></summary>',
    );
    expect(html).toContain('<span class="flag ok"></span><span class="who">talos · p95</span>');
  });

  it('marks every indicator ok when all of them are at or under their ceiling', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [indicator({ current: 2000 })],
        targets: [{ indicatorId: 'latency-p95', app: 'pragma', ceiling: 2000 }],
      }),
    );
    expect(html).toContain('<span class="score ok">1/1 ok</span>');
    expect(html).toContain('title="latency-p95 · at or under the ceiling of 2000 ms"');
  });

  it('hides the eight-week trend behind the indicator and scales it to the busiest week', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({
            weeks: [
              { weekStart: '2026-09-28', value: null },
              { weekStart: '2026-10-05', value: 0 },
              { weekStart: '2026-10-12', value: 4 },
            ],
          }),
        ],
      }),
    );
    expect(html).toContain(
      '</summary><div class="bars small" aria-label="eight-week trend"><span class="bar missing" title="week of 2026-09-28: no data"></span><span class="bar zero" style="height:0%" title="week of 2026-10-05: 0"></span><span class="bar" style="height:100%" title="week of 2026-10-12: 4"></span></div></details>',
    );
  });

  it('draws a flat row with no toggle when no week holds a value', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [indicator({ weeks: [{ weekStart: '2026-10-12', value: null }] })],
      }),
    );
    expect(html).toContain(
      '<div class="indicator flat" title="latency-p95 · no ceiling in docs/quality/targets.md, so neither ok nor ko"><span class="flag unjudged"></span><span class="who">pragma · p95</span><span class="amount">1391 ms</span></div>',
    );
    expect(html).not.toContain('aria-label="eight-week trend"');
  });

  it('says in the tooltip why an indicator holds no value', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({
            app: 'a',
            current: null,
            status: { kind: 'unavailable', reason: 'token <expired>' },
          }),
          indicator({
            app: 'b',
            current: null,
            status: { kind: 'not-applicable', reason: 'no API' },
          }),
          indicator({ app: 'c', current: null, weeks: [{ weekStart: '2026-10-12', value: 3 }] }),
        ],
      }),
    );
    expect(html).toContain('title="latency-p95 · token &lt;expired&gt;"');
    expect(html).toContain('title="latency-p95 · no API"');
    expect(html).toContain('title="latency-p95 · no traffic in the rolling seven days"');
    expect(html).toContain('<span class="amount">—</span>');
  });

  it('warns inside the section whose source could not be read, once per reason', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({ id: 'audit-other', pillar: 'security', app: 'repository' }),
          indicator({
            id: 'dependabot-other',
            pillar: 'security',
            app: 'repository',
            current: null,
            status: { kind: 'unavailable', reason: 'the token lacks the permission' },
          }),
          indicator({
            id: 'dependabot-critical-high',
            pillar: 'security',
            app: 'repository',
            current: null,
            status: { kind: 'unavailable', reason: 'the token lacks the permission' },
          }),
          indicator({
            id: 'secret-scanning-open',
            pillar: 'security',
            app: 'repository',
            current: null,
            status: { kind: 'unavailable', reason: 'the proxy refuses the path' },
          }),
        ],
      }),
    );
    expect(html).toContain(
      '<span class="warn" role="img" aria-label="a source could not be read" title="the token lacks the permission · the proxy refuses the path">⚠</span></summary>',
    );
    expect(html).toContain('<h2>Speed</h2><span class="score unjudged">0/0 ok</span></summary>');
  });

  it('ends with the engaged weak points and the defect map, both captioned by tooltip', () => {
    const html = renderDashboardPage(buildInput());
    expect(html).toContain(
      '<h2 title="Each weak point engaged in docs/quality/weak-points.md, with the dantotsus that recorded it, week by week. Target: zero per week.">Engaged weak points</h2>',
    );
    expect(html).toContain('>Defect map</h2>');
    expect(html).toContain('a bug report filed in pragma is stage E');
    expect(html).toContain('<h3 title="Applications and infrastructure packages by layer');
    expect(html).toContain(
      '<span title="A: caught locally or by a gate"><span class="dot stage-a">',
    );
  });
});
