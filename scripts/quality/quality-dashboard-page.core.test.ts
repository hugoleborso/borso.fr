import { describe, expect, it } from 'vitest';
import { renderDashboardPage, type DashboardPageInput } from './quality-dashboard-page.core';
import type { Indicator } from './quality-dashboard.core';

const NOW = '2026-10-13';

function indicator(overrides: Partial<Indicator>): Indicator {
  return {
    id: 'latency-p95',
    pillar: 'speed',
    label: 'API latency p95, 7 days',
    unit: 'ms',
    app: 'pragma',
    current: 1391,
    weeks: [
      { weekStart: '2026-10-05', value: 1000 },
      { weekStart: '2026-10-12', value: 2000 },
    ],
    status: { kind: 'ok' },
    ...overrides,
  };
}

function buildInput(overrides: Partial<DashboardPageInput> = {}): DashboardPageInput {
  return {
    now: NOW,
    indicators: [indicator({})],
    targets: [],
    unavailableSources: [],
    placed: [],
    engaged: [],
    weeklyCounts: new Map(),
    ...overrides,
  };
}

describe('renderDashboardPage', () => {
  it('opens with the title, the generation line and the note on targets', () => {
    const html = renderDashboardPage(buildInput());
    expect(html).toContain('<title>Quality dashboard</title>');
    expect(html).toContain(
      '<p>Generated by scripts/quality/quality-dashboard.ts on 2026-10-13. Each value covers the last seven days; the bars beside it are the last eight weeks, oldest first. No target is set yet, so no value is coloured.',
    );
    expect(html).not.toContain('class="banner"');
    expect(html).toContain('docs/quality/targets.md.</p>\n\n<div class="pillars">');
  });

  it('draws the three pillars in order, each with its own indicators', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({}),
          indicator({
            id: 'errors-prod',
            pillar: 'stability',
            label: 'Errors',
            unit: 'count',
            current: 3,
          }),
          indicator({
            id: 'dependabot',
            pillar: 'security',
            label: 'Alerts',
            unit: 'count',
            app: 'repository',
            current: 0,
            weeks: [{ weekStart: '2026-10-12', value: null }],
          }),
        ],
      }),
    );
    expect(html.indexOf('<h2>Security</h2>')).toBeLessThan(html.indexOf('<h2>Stability</h2>'));
    expect(html.indexOf('<h2>Stability</h2>')).toBeLessThan(html.indexOf('<h2>Speed</h2>'));
    expect(html).toContain(
      '<section class="pillar"><h2>Security</h2><p>Known vulnerable dependencies and exposed secrets, counted, never named.</p><div class="scroll"><table><tr><th></th><th>Alerts</th></tr><tr><th>repository</th><td><span class="value">0</span></td></tr></table></div></section>',
    );
    expect(html).toContain('<tr><th>pragma</th><td><span class="value">3</span>');
    expect(html).toContain('<span class="value">1391 ms</span>');
  });

  it('scales the trend to the busiest week and marks an empty week as missing', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({
            weeks: [
              { weekStart: '2026-09-28', value: null },
              { weekStart: '2026-10-05', value: 0 },
              { weekStart: '2026-10-12', value: 4 },
            ],
          }),
        ],
      }),
    );
    expect(html).toContain(
      '<div class="bars small" aria-label="eight-week trend"><span class="bar missing" title="week of 2026-09-28: no data"></span><span class="bar zero" style="height:0%" title="week of 2026-10-05: 0"></span><span class="bar" style="height:100%" title="week of 2026-10-12: 4"></span></div>',
    );
  });

  it('scales an all-zero trend to one and draws no trend when no week has data', () => {
    const zeros = renderDashboardPage(
      buildInput({ indicators: [indicator({ weeks: [{ weekStart: '2026-10-12', value: 0 }] })] }),
    );
    expect(zeros).toContain('style="height:0%"');
    const empty = renderDashboardPage(
      buildInput({
        indicators: [indicator({ weeks: [{ weekStart: '2026-10-12', value: null }] })],
      }),
    );
    expect(empty).toContain('<span class="value">1391 ms</span></td>');
  });

  it('says why a cell holds no value', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [
          indicator({
            app: 'a',
            current: null,
            status: { kind: 'unavailable', reason: 'token <expired>' },
          }),
          indicator({
            app: 'b',
            current: null,
            status: { kind: 'not-applicable', reason: 'no API' },
          }),
          indicator({ app: 'c', current: null }),
        ],
      }),
    );
    expect(html).toContain('<span class="status">unavailable: token &lt;expired&gt;</span>');
    expect(html).toContain('<tr><th>b</th><td><span class="status">no API</span></td></tr>');
    expect(html).toContain('<tr><th>c</th><td><span class="status">no traffic</span></td></tr>');
  });

  it('leaves a cell empty when an application has no such indicator', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [indicator({ app: 'a' }), indicator({ app: 'b', label: 'Other' })],
      }),
    );
    expect(html).toContain(
      '<tr><th></th><th>API latency p95, 7 days</th><th>Other</th></tr><tr><th>a</th>',
    );
    expect(html).toContain('</td></tr><tr><th>b</th><td></td><td>');
    expect(html).toContain('</section><section class="pillar"><h2>Stability</h2>');
  });

  it('colours a value against its target', () => {
    const html = renderDashboardPage(
      buildInput({
        indicators: [indicator({ app: 'a', current: 10 }), indicator({ app: 'b', current: 30 })],
        targets: [
          { indicatorId: 'latency-p95', app: 'a', ceiling: 20 },
          { indicatorId: 'latency-p95', app: 'b', ceiling: 20 },
        ],
      }),
    );
    expect(html).toContain('<span class="value within">10 ms</span>');
    expect(html).toContain('<span class="value over">30 ms</span>');
    expect(html).toContain('A value is green within its target and red over it');
  });

  it('lists the sources that could not be read in a banner', () => {
    const html = renderDashboardPage(
      buildInput({ unavailableSources: ['Sentry: <401>', 'Dependabot: 403'] }),
    );
    expect(html).toContain(
      '<div class="banner" role="status"><strong>Some sources could not be read on this run.</strong><ul><li>Sentry: &lt;401&gt;</li><li>Dependabot: 403</li></ul></div>',
    );
  });

  it('ends with the engaged weak points and the defect map', () => {
    const html = renderDashboardPage(buildInput());
    expect(html).toContain('<h2>Engaged weak points</h2>\n<p>No weak point is engaged.</p>');
    expect(html).toContain('<h2>Defect map</h2>');
    expect(html).toContain('a bug report filed in pragma is stage E');
    expect(html).toContain('<h3>Product map</h3>');
  });
});
