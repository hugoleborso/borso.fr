import type { DefectDot, EngagedWeakPoint } from './weak-points.core';

const NOW = '2026-10-13';

function indicator(overrides: Partial<Indicator>): Indicator {
  return {
    id: 'latency-p95',
    pillar: 'speed',
    label: 'p95',
    unit: 'ms',
    app: 'pragma',
    current: 1391,
    points: [
      { label: '2026-10-05', value: 1000 },
      { label: '2026-10-12', value: 2000 },
    ],
    status: { kind: 'ok' },
    ...overrides,
  };
}

function weakPoint(overrides: Partial<EngagedWeakPoint>): EngagedWeakPoint {
  return {
    id: 'gate-measures-nothing',
    title: 'A gate reports green while measuring nothing',
    map: 'factory',
    engagedOn: '2026-10-10',
    countermeasure: 'Plant one defect per gate',
    isClosed: false,
    ...overrides,
  };
}

function placedDot(overrides: Partial<DefectDot>, map: PlacedDot['map']): PlacedDot {
  return {
    dot: {
      slug: 'a-defect',
      title: 'A defect',
      date: '2026-10-12',
      zone: 'apps/pragma',
      weakPoint: null,
      recurs: [],
      stage: 'C',
      link: 'https://example.test/a',
      ...overrides,
    },
    map,
    row: map === 'product' ? 'apps/pragma' : 'gates',
    column: map === 'product' ? 'site' : 'defects',
  };
}

type InputOverrides = Partial<Omit<DashboardPageInput, 'ranges'>> & {
  readonly indicators?: readonly Indicator[];
  readonly ranges?: readonly RangeView[];
};

function buildInput(overrides: InputOverrides = {}): DashboardPageInput {
  const { indicators, ranges, ...rest } = overrides;
  return {
    now: NOW,
    ranges: ranges ?? [
      { id: 'week', title: 'week by week', indicators: indicators ?? [indicator({})] },
    ],
    security: [],
    targets: [],
    placed: [],
    engaged: [],
    weeklyCounts: new Map(),
    ...rest,
  };
}

function section(html: string, pattern: RegExp): string {
  return pattern.exec(html)?.[0] ?? '(no match)';
}

function axisTicks(value: number): readonly (string | undefined)[] {
  const html = renderDashboardPage(
    buildInput({
      indicators: [indicator({ unit: 'count', points: [{ label: 'w', value }] })],
    }),
  );
  return [...html.matchAll(/<span class="tick" style="bottom:[0-9]+%">([^<]+)</g)].map(
    (match) => match[1],
  );
}

